# 7.4 ABO血型遗传查询
def 判断血型(基因型):
    有A = False
    有B = False
    for 碱基 in 基因型:
        if 碱基 == "A":
            有A = True
        if 碱基 == "B":
            有B = True
    if 有A and 有B:
        return "AB"
    if 有A:
        return "A"
    if 有B:
        return "B"
    return "O"

def ABO血型遗传查询():
    print()
    print("输入父母双方的血型（A、B、AB、O），本程序帮你算孩子可能的血型")
    print("输入 q 或 Q 退出")
    while True:
        输入内容 = input("请输入父母血型（用空格或逗号分开，如 A B）: ").strip()
        if 输入内容 == "q" or 输入内容 == "Q":
            print()
            print("已退出血型查询")
            print()
            break
        if 输入内容 == "":
            continue
        清理后 = 输入内容.upper()
        清理后 = 清理后.replace("，", ",").replace("、", ",").replace(" ", ",")
        部分列表 = 清理后.split(",")
        血型列表 = []
        for 项目 in 部分列表:
            if 项目 != "":
                血型列表.append(项目)
        if len(血型列表) != 2:
            print("请输入两个血型 例如: A B 或 AB,O")
            print()
            continue
        父方血型 = 血型列表[0]
        母方血型 = 血型列表[1]
        合法血型 = ["A", "B", "AB", "O"]
        if 父方血型 not in 合法血型 or 母方血型 not in 合法血型:
            print("血型只能是 A、B、AB、O")
            print()
            continue
        血型基因 = {"A": ["AA", "AO"], "B": ["BB", "BO"], "AB": ["AB"], "O": ["OO"]}
        父方基因 = 血型基因[父方血型]
        母方基因 = 血型基因[母方血型]
        孩子血型集合 = {}
        for 父基因型 in 父方基因:
            for 母基因型 in 母方基因:
                i = 0
                while i < 2:
                    j = 0
                    while j < 2:
                        孩子 = 父基因型[i] + 母基因型[j]
                        血型 = 判断血型(孩子)
                        孩子血型集合[血型] = True
                        j = j + 1
                    i = i + 1
        可能列表 = []
        不可能列表 = []
        for 血型 in 合法血型:
            if 血型 in 孩子血型集合:
                可能列表.append(血型)
            else:
                不可能列表.append(血型)
        print("父亲血型 " + 父方血型 + "，基因型可能是: " + " 或 ".join(父方基因))
        print("母亲血型 " + 母方血型 + "，基因型可能是: " + " 或 ".join(母方基因))
        print("孩子可能出现的血型: " + "、".join(可能列表))
        if len(不可能列表) > 0:
            print("孩子不可能出现的血型: " + "、".join(不可能列表))
        else:
            print("孩子不可能出现的血型: 无（四种血型都有可能）")
        print()


