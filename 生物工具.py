    print()
    print("════ " + 条目["中文名"] + "（" + 符号 + "）的同位素 ════")
    i = 0
    while i < len(条目["同位素"]):
        显示同位素记录(符号, 条目["同位素"][i])
        i = i + 1
    print("  ⚠ 未收录说明: " + 条目["未收录说明"])
    print()

