# 7.3 遗传杂交预测（棋盘格）
def 基因型合法(基因型):
    i = 0
    while i + 1 < len(基因型):
        第一 = 基因型[i]
        第二 = 基因型[i + 1]
        if not 第一.isalpha() or not 第二.isalpha():
            return False
        if 第一.lower() != 第二.lower():
            return False
        i = i + 2
    return True

def 生成配子(基因型):
    基因对列表 = []
    i = 0
    while i + 1 < len(基因型):
        基因对列表.append(基因型[i] + 基因型[i + 1])
        i = i + 2
    配子列表 = [""]
    for 基因对 in 基因对列表:
        等位基因 = []
        for 碱基 in 基因对:
            if 碱基 not in 等位基因:
                等位基因.append(碱基)
        新配子列表 = []
        for 旧配子 in 配子列表:
            k = 0
            while k < len(等位基因):
                新配子列表.append(旧配子 + 等位基因[k])
                k = k + 1
        配子列表 = 新配子列表
    return 配子列表

def 组合基因型(父配子, 母配子):
    结果 = ""
    i = 0
    while i < len(父配子):
        基因1 = 父配子[i]
        基因2 = 母配子[i]
        if 基因1.isupper() and not 基因2.isupper():
            结果 = 结果 + 基因1 + 基因2
        elif 基因2.isupper() and not 基因1.isupper():
            结果 = 结果 + 基因2 + 基因1
        else:
            结果 = 结果 + 基因1 + 基因2
        i = i + 1
    return 结果

def 计算表现型(基因型):
    表现型 = ""
    i = 0
    while i < len(基因型):
        基因1 = 基因型[i]
        基因2 = 基因型[i + 1]
        if 基因1.isupper() or 基因2.isupper():
            表现型 = 表现型 + 基因1.upper() + "_"
        else:
            表现型 = 表现型 + 基因1.lower() + 基因1.lower()
        i = i + 2
    return 表现型

def 遗传杂交预测():
    print()
    print("支持单基因（如 Aa x aa）和双基因（如 AaBb x AaBb）的杂交预测")
    print("大写字母代表显性基因，小写字母代表隐性基因，同一对基因必须用同一个字母")
    print("注意：基因字母请不要用 X 和 Y，避免和分隔符 x 冲突")
    print("输入 q 或 Q 退出")
    while True:
        输入内容 = input("请输入杂交组合（如 Aa x aa）: ").strip()
        if 输入内容 == "q" or 输入内容 == "Q":
            print()
            print("已退出遗传杂交预测")
            print()
            break
        if 输入内容 == "":
            continue
        清理后 = 输入内容.replace(" ", "").replace("×", "x")
        部分 = 清理后.split("x")
        if len(部分) != 2:
            print("格式看不懂 请用 x 或 × 把两个基因型分开，例如 Aa x aa")
            print()
            continue
        父方基因型 = 部分[0]
        母方基因型 = 部分[1]
        if len(父方基因型) != 2 and len(父方基因型) != 4:
            print("父方基因型 " + 父方基因型 + " 不合法（只能写 2 个或 4 个字母）")
            print()
            continue
        if len(母方基因型) != 2 and len(母方基因型) != 4:
            print("母方基因型 " + 母方基因型 + " 不合法（只能写 2 个或 4 个字母）")
            print()
            continue
        if len(父方基因型) != len(母方基因型):
            print("两个亲本的基因对数要一样（都写 1 对或都写 2 对）")
            print()
            continue
        if not 基因型合法(父方基因型) or not 基因型合法(母方基因型):
            print("基因型不合法 每一对基因必须是同一个字母的大小写（如 Aa、Bb）")
            print()
            continue
        位置一致 = True
        i = 0
        while i < len(父方基因型):
            if 父方基因型[i].lower() != 母方基因型[i].lower():
                位置一致 = False
            i = i + 1
        if not 位置一致:
            print("两个亲本每一对基因用的字母要相同（不能一个是 A/a 对，另一个是 B/b 对）")
            print()
            continue
        父方配子 = 生成配子(父方基因型)
        母方配子 = 生成配子(母方基因型)
        合子计数 = {}
        表现型计数 = {}
        for 父配子 in 父方配子:
            for 母配子 in 母方配子:
                后代基因型 = 组合基因型(父配子, 母配子)
                合子计数[后代基因型] = 合子计数.get(后代基因型, 0) + 1
                后代表现型 = 计算表现型(后代基因型)
                表现型计数[后代表现型] = 表现型计数.get(后代表现型, 0) + 1
        print()
        print("父方可产生的配子: " + "、".join(父方配子))
        print("母方可产生的配子: " + "、".join(母方配子))
        print()
        print("杂交棋盘格:")
        格宽 = len(父方基因型) + 2
        表头 = " " * 格宽 + "|"
        for 母配子 in 母方配子:
            表头 = 表头 + ("{:^" + str(格宽) + "}").format(母配子) + "|"
        print(表头)
        for 父配子 in 父方配子:
            行 = ("{:^" + str(格宽) + "}").format(父配子) + "|"
            for 母配子 in 母方配子:
                后代基因型 = 组合基因型(父配子, 母配子)
                行 = 行 + ("{:^" + str(格宽) + "}").format(后代基因型) + "|"
            print(行)
        print()
        基因型列表 = sorted(合子计数)
